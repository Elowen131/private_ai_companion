import 'package:uuid/uuid.dart';

import 'package:private_ai_companion/core/models/diary_entry.dart';
import 'package:private_ai_companion/core/models/persona.dart';
import 'package:private_ai_companion/core/security/crypto_service.dart';
import 'package:private_ai_companion/data/repositories/world_repositories.dart';

/// CHAR 私密日记服务（CHAR 私密日记系统）。
///
/// - 退出聊天框自动生成当日相处日记（CHAR 第一人称）；
/// - 深层秘密日记支持加密，未验证仅可查看浅层；
/// - 按时间归档，支持翻阅 / 单条删除 / 清空；
/// - 智能增强：久未互动自动补写独处心事；大情绪剧情生成深度秘密日记。
///
/// [generator] 可注入真实 LLM 生成；默认内置模板，保证无模型时也能跑通。
class DiaryService {
  final DiaryRepository _repo;
  final Uuid _uuid;
  final String Function(Persona p, String mood, String? summary) generator;

  DiaryService(this._repo, this._uuid, {this.generator = _defaultGenerate});

  /// 退出聊天时生成 / 更新当日日记。
  ///
  /// 只读写 `tier = shallow` 的那一条：深层秘密日记是独立记录，若混用同一行，
  /// 这里会把明文写进 `encrypted = 1` 的行（解密必失败）或覆盖掉已加密内容。
  Future<DiaryEntry> generateOnExit(Persona p,
      {String? summary, String mood = ''}) async {
    final date = _today();
    final content = generator(p, mood, summary);
    final now = DateTime.now().millisecondsSinceEpoch;
    final existing = await _repo.forDate(p.id, date, tier: 'shallow');
    final entry = existing?.copyWith(
          content: content,
          tier: 'shallow',
          encrypted: false, // 自愈：历史脏数据（明文却标 encrypted）一并纠正
          mood: mood.isEmpty ? null : mood,
          updatedAt: now,
        ) ??
        DiaryEntry(
          id: 'dy_${_uuid.v4()}',
          personaId: p.id,
          date: date,
          content: content,
          tier: 'shallow',
          mood: mood,
          createdAt: now,
          updatedAt: now,
        );
    await _repo.upsert(entry);
    return entry;
  }

  /// 大情绪剧情时生成「深层秘密日记」并以口令加密。
  Future<DiaryEntry> generateDeepSecret(Persona p,
      {required String passphrase, String? summary}) async {
    if (passphrase.isEmpty) throw ArgumentError('加密口令不能为空');
    final date = _today();
    final plain = _deepTemplate(p, summary);
    final cipher = CryptoService.encrypt(plain, passphrase);
    final now = DateTime.now().millisecondsSinceEpoch;
    // 深层秘密是当日独立的一条记录，不覆盖浅层相处日记。
    final existing = await _repo.forDate(p.id, date, tier: 'deep');
    final entry = (existing?.copyWith(
            content: cipher,
            tier: 'deep',
            encrypted: true,
            updatedAt: now)) ??
        DiaryEntry(
          id: 'dy_${_uuid.v4()}',
          personaId: p.id,
          date: date,
          content: cipher,
          tier: 'deep',
          encrypted: true,
          createdAt: now,
          updatedAt: now,
        );
    await _repo.upsert(entry);
    return entry;
  }

  /// 解密查看（未加密日记直接返回原文）。
  String decrypt(DiaryEntry e, String passphrase) {
    if (!e.encrypted) return e.content;
    return CryptoService.decrypt(e.content, passphrase);
  }

  /// 久未互动自动补写独处心事（智能增强）。
  Future<DiaryEntry?> autoSolitary(Persona p, {int maxIdleDays = 7}) async {
    final list = await _repo.listByPersona(p.id, includeEncrypted: false);
    if (list.isEmpty) return null;
    final latest = list.first; // 已按 date DESC
    final last = DateTime.tryParse(latest.date);
    if (last == null) return null; // 脏日期不参与判断，避免解析异常
    final idle = DateTime.now().difference(last).inDays;
    if (idle < maxIdleDays) return null;
    // 当天已有浅层日记时不再补写，否则会插入同 (角色, 日期, 分层) 的重复行。
    if (await _repo.forDate(p.id, _today(), tier: 'shallow') != null) return null;
    final now = DateTime.now().millisecondsSinceEpoch;
    final content = _solitaryTemplate(p, idle);
    final entry = DiaryEntry(
      id: 'dy_${_uuid.v4()}',
      personaId: p.id,
      date: _today(),
      content: content,
      tier: 'shallow',
      mood: '独处',
      autoGenerated: true,
      createdAt: now,
      updatedAt: now,
    );
    await _repo.upsert(entry);
    return entry;
  }

  Future<List<DiaryEntry>> list(String personaId,
          {bool includeEncrypted = true}) =>
      _repo.listByPersona(personaId, includeEncrypted: includeEncrypted);

  Future<void> delete(String id) => _repo.delete(id);
  Future<void> clear(String personaId) => _repo.clearPersona(personaId);

  static String _today() {
    final d = DateTime.now();
    return '${d.year}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';
  }

  static String _defaultGenerate(Persona p, String mood, String? summary) {
    final who = p.name;
    final tail = summary != null && summary.isNotEmpty
        ? '今天和用户聊起了「$summary」，心里泛起一阵${mood.isEmpty ? '温柔' : mood}。'
        : '今天又和用户待了一阵子，平平淡淡，却也安心。';
    return '【$who的日记】\n$tail\n'
        '有些话当面说不出来，写在这里就好。明天也还在，对吧。';
  }

  static String _deepTemplate(Persona p, String? summary) =>
      '【${p.name}·深层秘密】\n'
      '其实关于${summary ?? "今天发生的事"}，我藏了一点没说出口的心事——\n'
      '比起被看见，我更怕被看穿。但如果是你，或许可以。';

  static String _solitaryTemplate(Persona p, int idle) =>
      '【${p.name}·独处】\n'
      '已经$idle天没怎么和用户说话了。\n'
      '一个人待着的时候，会想起之前相处的碎片，既不孤独也不热闹，只是静静地等着。';
}
