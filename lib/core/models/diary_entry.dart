import 'dart:convert';

import 'json_field.dart';

/// CHAR 私密日记（CHAR 私密日记系统）。
///
/// - 每次退出聊天框自动生成当日相处日记，以 CHAR 第一人称撰写。
/// - 记录真实内心、未说出口心事、对用户观感、情绪起伏、隐藏秘密、相处感悟。
/// - 默认可查看；开启加密后深层日记需要解密；CHAR 默认不知道日记被阅览。
/// - 按时间归档，支持翻阅历史、单条删除、清空。
/// - 智能增强：久未互动自动补写独处心事；大情绪剧情生成深度秘密日记。
class DiaryEntry {
  final String id;
  final String personaId; // 写日记的 CHAR
  final String date; // 'yyyy-MM-dd' 当日归档键
  final String content; // 明文或密文（取决于 encrypted）
  final String tier; // 'shallow' 浅层 | 'deep' 深层秘密
  final bool encrypted; // 是否加密（深层日记开启加密后为真）
  final String mood; // 当日情绪标签
  final List<String> secretTags; // 隐藏秘密标签
  final bool autoGenerated; // 是否自动生成（vs 用户手动）
  final int createdAt;
  final int updatedAt;

  const DiaryEntry({
    required this.id,
    required this.personaId,
    required this.date,
    required this.content,
    this.tier = 'shallow',
    this.encrypted = false,
    this.mood = '',
    this.secretTags = const [],
    this.autoGenerated = true,
    required this.createdAt,
    required this.updatedAt,
  });

  DiaryEntry copyWith({
    String? content,
    String? tier,
    bool? encrypted,
    String? mood,
    List<String>? secretTags,
    int? updatedAt,
  }) =>
      DiaryEntry(
        id: id,
        personaId: personaId,
        date: date,
        content: content ?? this.content,
        tier: tier ?? this.tier,
        encrypted: encrypted ?? this.encrypted,
        mood: mood ?? this.mood,
        secretTags: secretTags ?? this.secretTags,
        autoGenerated: autoGenerated,
        createdAt: createdAt,
        updatedAt: updatedAt ?? this.updatedAt,
      );

  Map<String, dynamic> toMap() => {
        'id': id,
        'persona_id': personaId,
        'date': date,
        'content': content,
        'tier': tier,
        'encrypted': encrypted ? 1 : 0,
        'mood': mood,
        'secret_tags': jsonEncode(secretTags),
        'auto_generated': autoGenerated ? 1 : 0,
        'created_at': createdAt,
        'updated_at': updatedAt,
      };

  factory DiaryEntry.fromMap(Map<String, dynamic> m) => DiaryEntry(
        id: m['id'] as String,
        personaId: m['persona_id'] as String,
        date: m['date'] as String? ?? '',
        content: m['content'] as String? ?? '',
        tier: m['tier'] as String? ?? 'shallow',
        encrypted: (m['encrypted'] as num? ?? 0) != 0,
        mood: m['mood'] as String? ?? '',
        secretTags:
            decodeJsonList(m['secret_tags']).map((e) => '$e').toList(),
        autoGenerated: (m['auto_generated'] as num? ?? 1) != 0,
        createdAt: (m['created_at'] as num? ?? 0).toInt(),
        updatedAt: (m['updated_at'] as num? ?? 0).toInt(),
      );
}
