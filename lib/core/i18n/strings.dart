/// 按语言取文案；缺失翻译回退到简体中文（源语言），绝不返回 null 或空。
String trString(String key, String lang) {
  final map = kStrings[lang];
  if (map != null && map.containsKey(key)) return map[key]!;
  return kStrings['zh']![key] ?? key;
}
