library;

/// 三种互动模式（全局核心规则 #2）。
enum InteractionMode {
  /// 真实剧情模式：所有行为永久写入世界档案，变更羁绊 / 人生轨迹 / 家族 /
  /// 养成 / 事件，永久留存。
  story,

  /// 即兴扮演模式：仅临时互动玩梗，不存档，不改动真实世界数据、记忆与剧情。
  improv,

  /// 日常闲聊模式：纯对话，关闭养成 / 剧情 / 事件 / 羁绊变动相关全部功能。
  daily;

  String get label {
    switch (this) {
      case InteractionMode.story:
        return '真实剧情';
      case InteractionMode.improv:
        return '即兴扮演';
      case InteractionMode.daily:
        return '日常闲聊';
    }
  }

  /// 模式是否写入「世界档案」。即兴扮演永不写入，真实剧情全写，
  /// 日常闲聊仅写入对话本身、不写入世界走向。
  bool get persistsToWorld => this != InteractionMode.improv;
}

/// 双世界观（全局核心规则 #3）。
enum Worldview {
  /// 常规写实世界观：无血脉、灵脉、天命、超自然、宿命论。
  realistic,

  /// 非常规幻想世界观：完整保留血脉等级、灵脉、幻力、异能、种族特质、
  /// 宿命羁绊、命运拐点、逆天改命、次元变异、隔代觉醒全套设定。
  fantasy;

  String get label {
    switch (this) {
      case Worldview.realistic:
        return '常规写实';
      case Worldview.fantasy:
        return '非常规幻想';
    }
  }
}

/// 「世界走向」相关可变更维度。用于规则引擎按当前模式决定是否允许写入。
enum WorldAspect {
  /// 羁绊等级 / 关系变动
  bond,

  /// 人生轨迹 / 身份职业变化
  lifeTrajectory,

  /// 家族树 / 婚恋后代
  family,

  /// 养成（宠物、孩子、修炼成长）
  cultivation,

  /// 世界自运转事件
  events,

  /// 剧情推进 / 剧情线变更
  plot,

  /// 时序年龄 / 样貌气质变化
  growth,

  /// 记忆 / 对话记录本身（始终由模式控制，不属「世界走向」）
  memory;
}

